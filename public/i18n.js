export const DICT = { ko, en, ja };

// t('ago.min', { n: 3 }) → "3분 전" / "3m ago" / "3分前"
export function t(key, vars = {}) {
  const v = DICT[lang][key] ?? en[key] ?? ko[key];
  if (v == null) return key;
  if (typeof v === 'function') return v(vars);
  return v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

const ATTRS = [
  ['data-i18n', (e, text) => { e.textContent = text; }],
  ['data-i18n-title', (e, text) => { e.title = text; }],
  ['data-i18n-aria', (e, text) => { e.setAttribute('aria-label', text); }],
  ['data-i18n-placeholder', (e, text) => { e.placeholder = text; }],
];

// Fill every element under `root` (and root itself) marked with a data-i18n* key.
export function applyI18n(root = document) {
  for (const [attr, set] of ATTRS) {
    const list = [...root.querySelectorAll(`[${attr}]`)];
    if (root.nodeType === 1 && root.hasAttribute(attr)) list.unshift(root);
    for (const e of list) set(e, t(e.getAttribute(attr)));
  }
}
